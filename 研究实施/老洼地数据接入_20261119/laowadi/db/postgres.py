"""PostgreSQL connections for shared operational state and archive snapshots."""

from contextlib import contextmanager
import os
from pathlib import Path
import re
import sqlite3

from laowadi.storage import ROOT, connect


RUNTIME_FILES = {
    "laowadi_jobs.sqlite3", "laowadi_audit.sqlite3", "laowadi_reviews.sqlite3",
    "laowadi_sessions.sqlite3", "laowadi_proactive.sqlite3",
    "laowadi_checkpoints.sqlite3", "dag_checkpoints.sqlite3",
}
RUNTIME_LOCK = 71112043


def postgres_mode():
    mode = os.environ.get("LAOWADI_BACKEND", "sqlite").strip()
    if mode not in ("sqlite", "postgresql"):
        raise ValueError("LAOWADI_BACKEND 须为 sqlite 或 postgresql。")
    return mode == "postgresql"


def runtime_postgres(path):
    target = Path(path).resolve()
    return postgres_mode() and target.parent == (ROOT / "local").resolve() and target.name in RUNTIME_FILES


def runtime_exists(path):
    return bool(path) and (runtime_postgres(path) or Path(path).is_file())


def pg_connect(url=None, *, schema="public"):
    import psycopg

    dsn = url or os.environ.get("LAOWADI_DATABASE_URL")
    if not dsn or not dsn.startswith(("postgresql://", "postgresql+psycopg://")):
        raise ValueError("PostgreSQL 模式须显式设置 LAOWADI_DATABASE_URL。")
    conn = psycopg.connect(
        dsn.replace("postgresql+psycopg://", "postgresql://", 1),
        autocommit=True, connect_timeout=2,
        options=f"-c search_path={schema},public -c statement_timeout=12000 -c lock_timeout=5000",
        row_factory=_pg_rows,
    )
    return conn


class Row:
    """Support the positional and named access used by the existing archive readers."""

    def __init__(self, names, values):
        self.names = names
        self.values = values
        self.by_name = dict(zip(names, values))

    def keys(self):
        return self.names

    def __getitem__(self, key):
        return self.by_name[key] if isinstance(key, str) else self.values[key]

    def __iter__(self):
        return iter(self.values)


def _pg_rows(cursor):
    names = tuple(column.name for column in cursor.description or ())
    return lambda values: Row(names, values)


def _params(sql, params):
    return (sql.replace("%", "%%").replace("?", "%s"), params) if params else (sql, None)


class ArchiveConnection:
    def __init__(self, conn):
        self.conn = conn

    def execute(self, statement, parameters=()):
        return self.conn.execute(*_params(statement, parameters))


class RuntimeConnection(ArchiveConnection):
    """Preserve the operational stores' transaction semantics over PostgreSQL.

    PostgreSQL advisory transaction locks replace SQLite's single-writer lock.
    Reads remain concurrent. SQL here is application-owned, including DDL.
    """

    def __init__(self, conn, *, writable):
        super().__init__(conn)
        self.writable = writable
        self.active = False

    def _begin(self):
        if not self.active:
            self.conn.execute("BEGIN")
            self.active = True
            self.conn.execute("SELECT pg_advisory_xact_lock(%s)", (RUNTIME_LOCK,))

    def execute(self, statement, parameters=()):
        sql = statement.strip()
        if sql.upper() in ("BEGIN", "BEGIN IMMEDIATE"):
            self._begin()
            return None
        if match := re.fullmatch(r"PRAGMA table_info\((\w+)\)", sql, re.I):
            return self.conn.execute(
                "SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = %s",
                (match[1],),
            )
        if sql.startswith("PRAGMA "):
            raise ValueError("Unsupported runtime SQL pragma")
        verb = sql.split(None, 1)[0].upper()
        if verb not in ("SELECT", "EXPLAIN"):
            if not self.writable:
                raise ValueError("Runtime connection is read-only.")
            self._begin()
        if verb in ("CREATE", "ALTER"):
            sql = re.sub(r"\bINTEGER PRIMARY KEY AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql, flags=re.I)
            sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql, flags=re.I)
        if re.match(r"INSERT\s+OR\s+IGNORE\b", sql, re.I):
            sql = re.sub(r"^INSERT\s+OR\s+IGNORE", "INSERT", sql, flags=re.I) + " ON CONFLICT DO NOTHING"
        return super().execute(sql, parameters)

    def executescript(self, statements):
        for statement in statements.split(";"):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        if self.active:
            self.conn.execute("COMMIT")
            self.active = False

    def rollback(self):
        if self.active:
            self.conn.execute("ROLLBACK")
            self.active = False

    def close(self):
        self.conn.close()

    def __enter__(self):
        if self.writable:
            self._begin()
        return self

    def __exit__(self, exc_type, *_):
        if exc_type:
            self.rollback()
        else:
            self.commit()


@contextmanager
def archive_snapshot(url, snapshot=None):
    from psycopg import sql

    with pg_connect(url, schema="laowadi_archive") as conn:
        conn.execute("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY")
        if snapshot is not None:
            conn.execute(sql.SQL("SET TRANSACTION SNAPSHOT {}").format(sql.Literal(snapshot)))
        yield ArchiveConnection(conn)


def connect_runtime(path, *, writable=False, wal=False, explicit=False):
    if runtime_postgres(path):
        return RuntimeConnection(pg_connect(schema="laowadi_runtime"), writable=writable)
    if not wal:
        return connect(path, writable=writable)
    conn = sqlite3.connect(path, timeout=15, isolation_level=None if explicit else "DEFERRED")
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


@contextmanager
def runtime_transaction(path, *, wal=False):
    conn = connect_runtime(path, writable=True, wal=wal)
    try:
        with conn:
            yield conn
    finally:
        conn.close()


@contextmanager
def watcher_slot(path):
    if not runtime_postgres(path):
        yield True
        return
    with pg_connect() as conn:
        yield conn.execute("SELECT pg_try_advisory_lock(71112045)").fetchone()[0]


